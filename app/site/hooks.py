"""Keep edit links pointed at the original sources, never the build staging area,
and inline the figures under docs/diagrams/ so they take the page's colours."""
import re
from pathlib import Path

RAW_LINK = re.compile(r'href="((?:\.\./)*[\w/-]+)\.md"')
FIGURE = re.compile(r'<p><img alt="[^"]*" src="[^"]*diagrams/([\w-]+\.svg)"\s*/?></p>')


def on_page_content(html, page, config, files):
    """A figure embedded as an image becomes its SVG, inline: a file shown as an
    image cannot read the page's variables, so it would stay the light scheme."""
    figures = Path(config['docs_dir']) / 'diagrams'

    def inline(m):
        return '<figure class="diagram">' + (figures / m.group(1)).read_text().strip() + '</figure>'

    html = FIGURE.sub(inline, html)
    # a link to another page written in raw HTML (a generated table), as MkDocs would rewrite markdown's
    up = '' if Path(page.file.src_uri).stem in ('README', 'index') else '../'
    return RAW_LINK.sub(lambda m: f'href="{up}{m.group(1)}/"', html)


def _title(path):
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.startswith('# '):
            return line[2:].strip()
    return path.stem


def on_config(config):
    """A navigation entry that names a folder's README.md is that folder: the
    README is the section's own page and every other page in the folder is
    listed under it, alphabetically, by its title. The generated pages of the
    Supported sections are not written into mkdocs.yml by hand."""
    docs = Path(config['docs_dir'])

    def expand(item):
        if isinstance(item, dict):
            return {k: expand(v) for k, v in item.items()}
        if isinstance(item, list):
            return [expand(x) for x in item]
        if isinstance(item, str) and item.endswith('/README.md'):
            folder = docs / item[:-len('/README.md')]
            pages = sorted((p for p in folder.glob('*.md') if p.name != 'README.md'),
                           key=lambda p: _title(p).replace('τ', 't').replace('³', '3').lower())
            # only a folder of generated pages: a hand-written folder lists its pages itself
            if pages and all(p.read_text(encoding='utf-8').startswith('<!-- generated by') for p in pages):
                return [item] + [{_title(p): item[:-len('README.md')] + p.name} for p in pages]
        return item

    config['nav'] = expand(config['nav'])
    return config


def on_page_context(context, page, config, nav):
    # every page is staged from docs/ in the repository
    page.edit_url = config['repo_url'] + '/edit/main/docs/' + page.file.src_uri
    return context
