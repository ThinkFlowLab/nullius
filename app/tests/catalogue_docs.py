def _mark(m: str, why: str = "") -> str:
    """One cell of a matrix: the mark, the reason on hover when there is one."""
    return f'<abbr class="mark no" title="{_cell(why)}">{NO}</abbr>' if why else MARK[m]


def _cell(text) -> str:
    """One table cell: no pipes, no line breaks."""
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def _table(head: list, rows: list) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _grouped(groups: list, rows: list) -> str:
    """A table whose header has two rows: a group over its columns (a
    group of one column is one cell on both rows). HTML, since markdown
    tables cannot span columns; bare, since the site wraps every table so
    it scrolls on a narrow screen. Cells are HTML too: `code` is <code>."""
    def cell(c):
        return str(c).replace("|", "\\|").replace("\n", " ").strip()
    top, sub = [], []
    for title, cols in groups:
        if len(cols) == 1 and cols[0] == title:
            top.append(f'<th rowspan="2">{cell(title)}</th>')
        else:
            top.append(f'<th colspan="{len(cols)}" class="group">{cell(title)}</th>')
            sub += [f"<th>{cell(c)}</th>" for c in cols]
    out = ["<table>", "<thead><tr>" + "".join(top) + "</tr><tr>" + "".join(sub) + "</tr></thead>", "<tbody>"]
    out += ["<tr>" + "".join(f"<td>{cell(c)}</td>" for c in r) + "</tr>" for r in rows]
    out += ["</tbody></table>"]
    return "\n".join(out)


CODE_SPAN = re.compile(r"`([^`]+)`")
MD_LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def _html(text, breakable: bool = False) -> str:
    """Markdown code spans and links as HTML, for a cell of an HTML table.
    `breakable` lets a long package name or path wrap after each slash."""
    def code(m):
        inner = m.group(1).replace("/", "/<wbr>") if breakable else m.group(1)
        return f"<code>{inner}</code>"
    return MD_LINK.sub(lambda m: f'<a href="{m.group(2)}">{m.group(1)}</a>', CODE_SPAN.sub(code, str(text)))


def _facts(rows: list) -> str:
    """One entry's facts, a row per fact with its name in the first column,
    so the table reads whole on any screen. HTML, like :func:`_grouped`."""
    out = ["<table>", "<tbody>"]
    out += [f"<tr><th>{name}</th><td>{value}</td></tr>" for name, value in rows]
    out += ["</tbody></table>"]
    return "\n".join(out)


def _port_html(name: str) -> str:
    """A port's name as code that may wrap after a dot or a slash, so a column of ports stays narrow."""
    return "<code>" + name.replace(".", ".<wbr>").replace("/", "/<wbr>") + "</code>"


def _kitted(port_list: list) -> list:
    """The ports a matrix shows: those with a kit. A port defined ahead of its
    kit could only read *not tested* in every row."""
    return [(name, port) for name, port in port_list if port.get("kit")]


def _chips(names) -> str:
    return ", ".join(f"`{n}`" for n in names)


def _ref(d: dict) -> str:
    return d.get("_ref") or d["key"]


def _link(text: str, target: str) -> str:
    return f"[{text}]({target})"


def _page_of(d: dict) -> str:
    """The page of an agent, capability or benchmark, from its index: `<key>.md`."""
    return f"{d['key']}.md"


def _installed_from(d: dict) -> str:
    """What the install pins: the packages, or the repository at its commit."""
    inst, up = d.get("install") or {}, d.get("upstream") or {}
    if inst.get("npm"):
        return _chips(inst["npm"])
    if inst.get("pip") or inst.get("wheels"):
        return _chips(list(inst.get("pip") or []) + [x["url"].rsplit("/", 1)[1] for x in inst.get("wheels") or []])
    if inst.get("project") or up.get("repository"):
        repo = (up.get("repository") or "").replace("https://", "")
        return f"`{repo}` at `{str(up.get('tested', ''))[:12]}`" if repo else "a repository"
    return "nothing: runs on this machine's `python3`"


def _licence(d: dict) -> str:
    """The upstream's licence, or nothing when the definition does not say."""
    lic = (d.get("upstream") or {}).get("license", "")
    return "" if not lic or lic.lower() in ("unknown", "none") else lic


def _driven(d: dict) -> str:
    """ACP, naming the adapter when it is not the agent's own command; else a command."""
    start = d.get("start") or {}
    if "acp" not in start:
        return "a command"
    program = os.path.basename(start["acp"][0]) if start["acp"] else ""
    own = program in ("", d.get("key"), "python", "python3", "node", "uv", "uvx", "npx")
    return "ACP" if own else f"ACP via `{program}`"


def _from(d: dict) -> str:
    inst = d.get("install") or {}
    source = {"npm": "npm", "pip": "PyPI"}
    return next((source[k] for k in source if inst.get(k)),
                "repository" if inst.get("project") or (d.get("upstream") or {}).get("repository") else "")


def _offered(d: dict) -> list:
    """The ports a version has proven, in the standard's order."""
    proven = d.get("proven") or {}
    return [p for p in ports.PORTS if p in (d.get("offers") or []) and p in proven]


def _why(reasons: list) -> str:
    """The ports a refusal names, without the kit's summaries."""
    missing = []
    for r in reasons:
        for m in re.finditer(r"needs (\S+?)(?: \(|,)", r):
            if m.group(1) not in missing:
                missing.append(m.group(1))
        for m in re.finditer(r"has not shown the (\S+) skill of (\S+)", r):
            missing.append(f"the {m.group(1)} skill of {m.group(2)}")
    return "lacks " + ", ".join(f"`{m}`" if " " not in m else m for m in missing) if missing else "; ".join(reasons)


def _fits(benches: list, others: list) -> dict:
    """{benchmark key: {ref: reasons or []}} for every pair."""
    return match.table(benches, [o for o in others if o.get("_kind") == "agent"],
                       [o for o in others if o.get("_kind") == "capability"])


def _fit_matrix(benches: list, others: list, link=None) -> tuple:
    """An agent or capability per row, a benchmark per column over the ports it
    needs: ✓ when the pair fits, ✗ with the reason on hover when it does
    not. Groups and rows for :func:`_grouped`."""
    table = _fits(benches, others)
    groups = [("", [""])] + [(f'<a href="../../benchmarks/supported/{b["key"]}.md">{b.get("label") or b["key"]}</a>',
                              [", ".join(ports.PORTS[n]["label"] if n in ports.PORTS else f"<code>{n}</code>" for n in b.get("needs") or []) or "none"])
                             for b in benches]
    rows = []
    for o in others:
        fits = [table.get(b["key"], {}).get(_ref(o)) for b in benches]
        name = f"<code>{_ref(o)}</code>"
        href = link(o) if link else ""
        rows.append([f'<a href="{href}">{name}</a>' if href else name, *(_mark(YES) if not why else _mark(NO, _why(why)) for why in fits)])
    return groups, rows


def _load(kind: str, every: bool = True) -> list:
    out, bad = definitions.load(kind, root=definitions.CATALOGUE, every=every)
    if bad:
        raise SystemExit(f"{kind}: " + "; ".join(bad))
    return out


def _values(spec: dict) -> str:
    """An option's values, the default in bold; a pattern when it has no list."""
    values = ", ".join(f"**`{v}`**" if v == spec.get("default") else f"`{v}`" for v in spec.get("values") or [])
    return values or f"pattern `{spec.get('pattern')}`, default `{spec.get('default')}`"


def _needs_rows(name: str, spec: dict) -> list:
    return [[f"`{name}`", f"`{val}`", "; ".join(f"{k}: {', '.join(w) if isinstance(w, list) else w}" for k, w in need.items())]
            for val, need in (spec.get("needs") or {}).items()]



def _agent_ports() -> list:
    return [(name, port) for name, port in ports.PORTS.items() if port["family"] == "agent"]


def _port_row(d: dict, port_list: list, skills: list, port: str) -> list:
    """One row of a ports matrix: a mark per port, then per skill of `port`."""
    offered = _offered(d)
    shown = set(definitions.skills_shown(port, (d.get("proven") or {}).get(port)))
    return [*(_mark(YES if name in offered else UNTESTED if not p.get("kit") else NONE) for name, p in port_list),
            *(_mark((YES if sk in shown else NO) if port in offered else NONE) for sk in skills)]


def render_agents_index() -> str:
    agents = _load("agent")
    real = [a for a in agents if not a.get("example")]
    examples = [a for a in agents if a.get("example")]
    out = ["### Available agents", ""]
    seen, rows = set(), []
    for a in real:
        if a["key"] in seen:
            continue
        seen.add(a["key"])
        versions = [x for x in real if x["key"] == a["key"]]
        rows.append([_link(a.get("label", ""), _page_of(a)), _chips(_ref(v) for v in versions), a.get("summary", ""),
                     _driven(a), _from(a), _licence(a) or "not stated"])
    out += [_table(["Agent", "Versions (bare key: the default)", "What it is", "Driven over", "From", "Licence"], rows), "",
            "- ACP (`start.acp`) can prove task, workspace, tools and conversation; a command (`start.command` with `{prompt}`) task and workspace only."]
    if examples:
        out += ["- Examples, never offered for a run: "
                + "; ".join(f"`{_ref(a)}` ({a.get('label')}: {a.get('summary')})" for a in examples)]
    out += ["", "### Ports proven", ""]
    agent_ports = _agent_ports()
    out += [_table(["Port", "Label", "What it proves"], [[f"`{name}`", port["label"], port["summary"]] for name, port in agent_ports]), ""]
    skills = list(definitions.port_skills("agent.tools/v1"))
    kitted = _kitted(agent_ports)
    groups = [("Agent", ["Agent"]), ("Ports", [port["label"] for _, port in kitted]), ("Tools, the skills of <code>agent.tools/v1</code>", skills)]
    rows = [[f'<a href="{_page_of(a)}"><code>{_ref(a)}</code></a>' if not a.get("example") else f"<code>{_ref(a)}</code>",
             *_port_row(a, kitted, skills, "agent.tools/v1")] for a in agents]
    untested = [port["label"] for _, port in agent_ports if not port.get("kit")]
    out += [_grouped(groups, rows), "", LEGEND + " An agent that misses a skill still has the port."
            + (f" {', '.join(untested)} has no kit yet, so no agent is tested on it; it comes with the first benchmark that needs it." if untested else ""), ""]
    out += ["### Benchmarks each agent fits", ""]
    benches = [b for b in _load("benchmark", every=False) if b.get("family") == "agent"]
    out += _fit_block(benches, agents, lambda o: _page_of(o) if not o.get("example") else "")
    out += ["### Harbor agents", "",
            "Every agent `harbor agents list` finds in the pinned Harbor, as *Harbor built-in*, and the builder's own:", ""]
    rows = [[f"`{a['id']}`", a.get("kind", ""), a.get("summary", "")] for a in launch.AGENTS]
    out += [_table(["Agent", "Kind", "What it does"], rows), ""]
    return "\n".join(out).rstrip() + "\n"


def render_agent_page(versions: list) -> str:
    """One agent's page: its versions in the file's order, the default first in the summary."""
    a = next((v for v in versions if v.get("_version") == v.get("_default")), versions[0])
    core = (a.get("upstream") or {}).get("core")
    out = [PAGE_MARK, "", f"# {a.get('label', a['key'])}", "", a.get("summary", ""), ""]
    facts = [("Key", f"<code>{a['key']}</code>"), ("Driven over", _html(_driven(a))), ("From", _from(a) or "this repository"),
             ("Installed", _html(_installed_from(a), breakable=True)), ("Licence", _licence(a) or "not stated")]
    out += [_facts(facts + ([("Core", _html(core))] if core else [])), ""]
    out += ["## Versions", ""]
    kitted = _kitted(_agent_ports())
    skills = list(definitions.port_skills("agent.tools/v1"))
    groups = [("Version", ["Version"]), ("Upstream", ["Upstream"]), ("Ports", [p["label"] for _, p in kitted]), ("Tools", skills)]
    rows = []
    for v in versions:
        name = f"<code>{_ref(v)}</code>" + (" (default)" if len(versions) > 1 and v.get("_version") == v.get("_default") else "")
        rows.append([name, f"<code>{(v.get('upstream') or {}).get('version', '')}</code>", *_port_row(v, kitted, skills, "agent.tools/v1")])
    out += [_grouped(groups, rows), ""] + ([VERSION_NOTE, ""] if len(versions) > 1 else [])
    options = {}
    for v in versions:
        for name, spec in sorted((v.get("options") or {}).items()):
            options.setdefault(name, (spec, []))[1].append(_ref(v))
    out += ["## Options", ""]
    if options:
        rows = [[f"`{name}`", _values(spec), _cell(spec.get("summary", "")), "every version" if len(vs) == len(versions) else _chips(vs)]
                for name, (spec, vs) in options.items()]
        out += [_table(["Option", VALUES, "What it sets", "Versions"], rows), ""]
    else:
        out += ["None declared.", ""]
    out += ["## Benchmarks it fits", ""]
    benches = [b for b in _load("benchmark", every=False) if b.get("family") == "agent"]
    out += _fit_block(benches, versions)
    return "\n".join(out).rstrip() + "\n"


def _fit_block(benches: list, others: list, link=None) -> list:
    """A fit matrix, its legend only when a pair does not fit."""
    groups, rows = _fit_matrix(benches, others, link)
    return [_grouped(groups, rows), ""] + ([MISSING, ""] if any(NO in c for r in rows for c in r) else [])



