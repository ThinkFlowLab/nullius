YES, NO, NONE, UNTESTED = "✓", "✗", "–", "not tested"
MARK = {YES: '<span class="mark">✓</span>', NO: '<span class="mark no">✗</span>', NONE: '<span class="mark none">–</span>',
        UNTESTED: '<span class="mark none">not tested</span>'}
