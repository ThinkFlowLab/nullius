def _origin(entry) -> str:
    """Official or Experiment, linked to the benchmark's own repository."""
    url = (entry.citation_source or "").strip()
    return f'<a href="{url}">{entry.label}</a>' if url.startswith("http") else entry.label


def _paper(entry) -> str:
    """The first paper of its citation, linked, with its venue and year."""
    papers = citation.parse(entry.citation)
    if not papers:
        return ""
    p = papers[0]
    title = _link(p["title"], p["url"]) if p.get("url") else p["title"]
    where = " · ".join(x for x in (p.get("venue_short"), p.get("year")) if x)
    return f"{title}, {where}" if where else title


def _dataset_from(d, entry, std_def) -> str:
    """Where a dataset's data comes from, each way linked when the source has an address."""
    parts = []
    for row in sources.of(d, entry.harness, std_def, only=len(entry.datasets) == 1):
        name = f"`{row['name']}`" if row.get("name") else ""
        if row.get("href"):
            name = _link(row["name"], row["href"])
        parts.append(f"{row['from']} {name}".strip())
    return "<br>".join(parts) or d.source


HARBOR_CONTROLS = {"nop": "Harbor", "oracle": "the authors"}


def _controls(d: dict, entry=None) -> dict:
    """Who wrote each control, by name: the standard definition's, else, for a
    benchmark Harbor runs, Harbor's own two agents - `nop` is Harbor's and does
    nothing; `oracle` applies the task's reference solution, the authors'."""
    controls = (d or {}).get("controls") or {}
    if controls:
        return {c: SOURCES.get(controls[c].get("source"), controls[c].get("source")) for c in definitions.CONTROLS if c in controls}
    if entry is not None and "harbor" in entry.harness:
        return dict(HARBOR_CONTROLS)
    return {}


def _ways(versions: list, entry=None) -> tuple:
    """Whether the benchmark runs as published, and whether that way takes a
    model of your choice: on the standard, an `original` setup, and a `model`
    setup or an `original` that fixes no models (`models` absent: any); on
    Harbor, the upstream's own agent the entry names (`published`), which
    runs on any model."""
    setups = {}
    for v in versions:
        setups.update(v.get("setups") or {})
    if setups:
        return True, "model" in setups or "models" not in (setups.get("original") or {})
    if entry is not None and entry.published:
        return True, True
    return False, False


def _setups(v: dict) -> str:
    """One procedure with independent participant and model choices."""
    setups = v.get("setups") or {}
    original = setups.get("original")
    if not original:
        return "none"
    fixed = original.get("models") or v.get("simulator") or (v.get("score") or {}).get("judge")
    model_choice = ", ".join((["Like the paper"] if fixed else []) + (["Like the leaderboard"] if v.get("leaderboard") else []) + ["Any of your choice"])
    model_choice = " or ".join(model_choice.rsplit(", ", 1))
    participant = original.get("reference_agent") or ("Original memory" if v.get("family") == "capability" else "No agent")
    return f"Original · {participant} · {model_choice}"


def _standard_of(key: str):
    """The raw standard definition beside the entry, as the page reads it."""
    return definitions.find(definitions.load("benchmark", root=definitions.CATALOGUE)[0], key)


def render_benchmarks_index() -> str:
    cat = catalog.load(root=catalog.ROOT)
    entries = sorted(cat.benchmarks, key=lambda b: catalog.sort_key(b.title))
    by_key = {b["key"]: b for b in _load("benchmark", every=False)}
    versions = {}
    for b in _load("benchmark", every=True):
        versions.setdefault(b["key"], []).append(b)
    out = ["### Available benchmarks", ""]
    rows = []
    for b in entries:
        sets = [d for d in cat.datasets if d.benchmark == b.key]
        tasks = sum(d.tasks for d in sets if isinstance(d.tasks, int))
        rows.append([f'<a href="{b.key}.md">{b.title}</a><br><code>{b.key}</code>', f'<span class="what">{b.domain or b.scoring}</span>', b.category,
                     MARK[YES if "standard" in b.harness else NONE], MARK[YES if "harbor" in b.harness else NONE], tasks, _origin(b)])
    out += [_grouped([("Benchmark", ["Benchmark"]), ("What it is", ["What it is"]), ("Category", ["Category"]),
                      ("Runs on", [RUNNERS["standard"], RUNNERS["harbor"]]), ("Tasks", ["Tasks"]), ("Origin", ["Origin"])], rows), ""]
    out += ["### How each runs", ""]
    rows = []
    for b in entries:
        d = by_key.get(b.key) or {}
        controls = _controls(d, b)
        pipeline, your_model = _ways(versions.get(b.key, []), b)
        rows.append([f'<a href="{b.key}.md">{b.title}</a>',
                     ", ".join(_port_html(n) for n in d.get("needs") or []) or ("a Harbor agent" if not d else ""),
                     *(controls.get(c, MARK[NONE]) for c in definitions.CONTROLS),
                     MARK[YES], MARK[YES if pipeline else NONE], MARK[YES if your_model else NONE]])
    out += [_grouped([("Benchmark", ["Benchmark"]), ("Needs, ports proven", ["Needs, ports proven"]),
                      ("Controls, written by", list(definitions.CONTROLS)),
                      ("Runs with, any model", ["your agent or capability", "as published", "as published, your model"])], rows), "",
            "- Nullius wrote a control where the upstream published none."
            + (" On Harbor alone, `nop` is Harbor's own agent and `oracle` applies the task's reference solution."
               if any(b.key not in by_key for b in entries) else ""),
            "- As published: the upstream's own answering program (on Harbor, its own agent) with the models its paper fixes; "
            "your model, where the paper's are not served.", ""]
    return "\n".join(out).rstrip() + "\n"


def render_benchmark_page(entry, cat, by_key: dict, versions: list) -> str:
    d = by_key.get(entry.key)
    std_def = _standard_of(entry.key) if d else None
    out = [PAGE_MARK, "", f"# {entry.title}", "", entry.domain or entry.scoring, ""]
    sets = cat.datasets_of(entry)
    tasks = sum(x.tasks for x in sets if isinstance(x.tasks, int))
    facts = [("Key", f"<code>{entry.key}</code>"), ("Category", entry.category), ("Origin", _origin(entry)),
             ("Runs on", ", ".join(RUNNERS[h] for h in RUNNERS if h in entry.harness)), ("Tasks", str(tasks)), ("Paper", _html(_paper(entry)))]
    out += [_facts(facts + ([("Needs, ports proven", ", ".join(_port_html(n) for n in d.get("needs") or []) or "nothing")] if d else [])), ""]
    out += ["## Datasets", ""]
    rows = [[x.title, f"`{x.key}`", x.tasks, _dataset_from(x, entry, std_def), x.verifier] for x in sets]
    out += [_table(["Dataset", "Key", "Tasks", "From", "Verifier"], rows) if rows else "None recorded.", ""]
    if d:
        out += ["## On the standard", ""]
        rows = [[f"`{c}`", who] for c, who in _controls(d, entry).items()]
        out += [_table(["Control", "Written by"], rows) if rows else "No control.", ""]
        out += ["### Versions", ""]
        rows = []
        for v in versions:
            name = f"`{_ref(v)}`" + (" (default)" if len(versions) > 1 and v.get("_version") == v.get("_default") else "")
            rows.append([name, _setups(v), _chips(sorted(v.get("options") or {})) or "none"])
        out += [_table(["Version", "Setups as published, whose model", "Options"], rows), ""]
        out += [VERSION_NOTE, ""] if len(versions) > 1 else []
        seen, rows, needy = set(), [], []
        for v in sorted(versions, key=lambda v: v.get("_version") != d.get("_version")):
            for name, spec in sorted((v.get("options") or {}).items()):
                if name in seen:
                    continue
                seen.add(name)
                rows.append([f"`{name}`", _values(spec), _cell(spec.get("summary", "")), _chips(spec.get("setups") or []) or "yours"])
                needy += _needs_rows(name, spec)
        if rows:
            out += ["## Options", "", _table(["Option", VALUES, "What it sets", "Setups"], rows), ""]
        if needy:
            out += [_table(["Option", "Value", "Refused without (`host`: the driver's machine; `embeddings`: a model the provider serves)"], needy), ""]
    if not d and "harbor" in entry.harness:
        does = {"nop": "nothing", "oracle": "applies the task's reference solution"}
        out += ["## On Harbor", "", _table(["Control", "Written by", "Does, with no model"],
                                            [[f"`{c}`", who, does[c]] for c, who in _controls(d, entry).items()]), ""]
    if entry.published:
        out += ["## As published", "",
                _table(["Harbor agent, among the builder's", "Model", "What it is"], [[f"`{entry.published['agent']}`", "any", entry.published["says"]]]), ""]
    if entry.good_to_know:
        out += ["## Good to know", ""]
        out += [f"- {_cell(note)}" for note in entry.good_to_know] + [""]
    if entry.upstream_limitations:
        out += ["## Upstream limitations", ""]
        out += [f"- {_cell(l)}" for l in entry.upstream_limitations] + [""]
    if entry.limitations:
        out += ["## Nullius limitations", ""]
        out += [f"- {_cell(l)}" for l in entry.limitations] + [""]
    if entry.citation:
        out += ["## Cite", "", '??? citation "BibTeX"', "", "    ```bibtex"]
        out += ["    " + line for line in entry.citation.strip().splitlines()]
        out += ["    ```", ""]
    return "\n".join(out).rstrip() + "\n"



INDEXES = {"agents": render_agents_index, "benchmarks": render_benchmarks_index, "capabilities": render_features_index}


def render_pages(kind: str) -> dict:
    """{file name: text} for every entry's page of a kind."""
    if kind == "benchmarks":
        cat = catalog.load(root=catalog.ROOT)
        by_key = {b["key"]: b for b in _load("benchmark", every=False)}
        versions = {}
        for b in _load("benchmark", every=True):
            versions.setdefault(b["key"], []).append(b)
        return {f"{b.key}.md": render_benchmark_page(b, cat, by_key, versions.get(b.key, [])) for b in cat.benchmarks}
    render = render_agent_page if kind == "agents" else render_feature_page
    groups = {}
    for d in _load("agent" if kind == "agents" else "capability"):
        if not d.get("example"):
            groups.setdefault(d["key"], []).append(d)
    return {f"{key}.md": render(versions) for key, versions in groups.items()}


def apply(text: str, block: str) -> str:
    """`text` with its generated block replaced by `block`."""
    a, b = text.find(START), text.find(END)
    if a < 0 or b < 0 or b < a:
        raise ValueError("the page has no generated block: markers missing")
    return text[:a] + START + "\n\n" + block.rstrip() + "\n\n" + END + text[b + len(END):]


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _wanted() -> dict:
    """{path: text} for every file the catalogue renders: the index with its
    block applied, and each page; a page in a section's folder that no entry
    renders is an orphan, given as None."""
    out = {}
    for kind, folder in SECTIONS.items():
        index = os.path.join(folder, INDEX)
        out[index] = apply(_read(index), INDEXES[kind]()) if os.path.exists(index) else None
        pages = render_pages(kind)
        for name, text in pages.items():
            out[os.path.join(folder, name)] = text
        for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            if name.endswith(".md") and name != INDEX and name not in pages:
                out[os.path.join(folder, name)] = None
    return out


def stale() -> list:
    """The files that are not what the catalogue renders now: a block or a
    page that differs, a page missing, an orphan page, an index missing."""
    out = []
    for path, text in _wanted().items():
        current = _read(path) if os.path.exists(path) else None
        if current != text:
            out.append(os.path.relpath(path, REPO))
    return out


def write() -> list:
    out = []
    for path, text in _wanted().items():
        current = _read(path) if os.path.exists(path) else None
        if current == text:
            continue
        if text is None:
            if current is not None:
                os.remove(path)
                out.append("removed " + os.path.relpath(path, REPO))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        out.append("wrote " + os.path.relpath(path, REPO))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true", help="refresh the generated blocks and pages")
    args = ap.parse_args()
    if args.write:
        for p in write():
            print(p)
        return 0
    bad = stale()
    for p in bad:
        print("stale", p)
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
